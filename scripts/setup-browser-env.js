/**
 * Generate .env.browser, the environment the Playwright suite runs against.
 *
 * This exists because the values the browser environment needs are not
 * defaults. Hand-writing them in the README is how they drift: an earlier
 * version of that setup note said "cp .env.example .env.browser, then set
 * APP_KEY and DB_DATABASE", which leaves eight further keys wrong.
 *
 * Two of those are silent rather than loud:
 *
 *   APP_ENV=local  means app()->environment('browser') is false, so
 *                  BrowserFixturesSeeder never runs and every test that
 *                  asserts on a named record fails on a fresh clone.
 *   CACHE_STORE=database  makes the sign-in throttle count persist in the
 *                  database between runs, so a suite that signs in more
 *                  than five times locks itself out.
 *
 * Neither produces an error message explaining itself. Generating the file
 * means the values are decided in one place, and a key added to .env.example
 * later is picked up automatically instead of being missed.
 *
 * Safe to re-run: it never touches .env, only .env.browser.
 *
 * Usage: npm run browser:setup
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const TARGET = '.env.browser';

/**
 * Every value the browser environment overrides, with why.
 *
 * Kept explicit rather than derived from the other environments, because each
 * one is a decision rather than a copy.
 */
const OVERRIDES = {
    // Named 'browser' so DatabaseSeeder runs BrowserFixturesSeeder, and so the
    // app is distinguishable from local at a glance in a stack trace.
    APP_ENV: 'browser',

    // Must match playwright.config.ts baseURL and the webServer url, or every
    // redirect and signed URL points somewhere the suite cannot reach.
    APP_URL: 'http://127.0.0.1:8123',

    // A disposable database of its own. The suite rebuilds this one from seed
    // on every run; sharing the development or PHPUnit database would destroy
    // data that belongs to neither.
    DB_DATABASE: 'govqueue_browser',

    // In-memory, so the sign-in throttle starts empty on every run and leaks
    // no rows into a database that is about to be dropped and rebuilt.
    CACHE_STORE: 'array',

    // File rather than database: the suite drops and recreates the schema
    // between runs, and a database-backed session store would point at tables
    // that no longer exist.
    SESSION_DRIVER: 'file',

    // No Reverb server during a browser run. Broadcasting to a dead socket
    // produces console errors on every page and can trip the circuit breaker,
    // which would change what the display tests are actually measuring.
    BROADCAST_CONNECTION: 'log',
    REVERB_HOST: '127.0.0.1',

    // Nothing should be sent or queued during a test run.
    MAIL_MAILER: 'array',
    QUEUE_CONNECTION: 'sync',

    // No .env key needed: the suite's fixture blocks all non-loopback requests.
    SMS_DRIVER: 'log',
};

if (!existsSync('.env.example')) {
    console.error('.env.example is missing. Cannot generate ' + TARGET + '.');
    process.exit(1);
}

if (existsSync(TARGET) && !process.argv.includes('--force')) {
    console.log(TARGET + ' already exists. Pass --force to overwrite it.');
    process.exit(0);
}

/*
 * Start from .env.example rather than writing a file from scratch, so a key
 * added there later - a new config value, a mail setting - reaches the browser
 * environment without anyone remembering to add it here too.
 */
let contents = readFileSync('.env.example', 'utf8');

for (const [key, value] of Object.entries(OVERRIDES)) {
    const line = key + '=' + value;
    const pattern = new RegExp('^' + key + '=.*$', 'm');

    contents = pattern.test(contents)
        ? contents.replace(pattern, line)
        : contents.replace(/\s*$/, '\n\n' + line + '\n');
}

/*
 * A fresh APP_KEY per environment, generated by the framework that will use it.
 *
 * Reusing .env's key would work and is quietly wrong: the reset-password links
 * the browser suite can reach would be signed by the same secret as the
 * development environment's.
 */
const php = process.platform === 'win32' ? 'php.exe' : 'php';

const key = execFileSync(php, ['artisan', 'key:generate', '--show'], {
    encoding: 'utf8',
}).trim();

contents = contents.replace(/^APP_KEY=.*$/m, 'APP_KEY=' + key);

writeFileSync(TARGET, contents, 'utf8');

console.log('Wrote ' + TARGET + ' with ' + Object.keys(OVERRIDES).length + ' overrides and a fresh APP_KEY.');
console.log('');
console.log('Still required, because this script cannot do it for you:');
console.log('');
console.log('  1. Create the database:');
console.log('       mysql -e "CREATE DATABASE govqueue_browser CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci"');
console.log('');
console.log('  2. Confirm DB_USERNAME and DB_PASSWORD above match your MySQL.');
console.log('');
console.log('  3. Then:');
console.log('       npm run test:browser');